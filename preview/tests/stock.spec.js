const { test, expect } = require("@playwright/test");
const fs = require("fs");
const P = `${process.env.FATMI_PREFIX || ""}${process.env.FATMI_PATH || "/preview/"}`;
const TUE_15 = "2026-11-10T15:00:00+07:00";
const url = `${P}?debug=1&sleep=8&now=${encodeURIComponent(TUE_15)}#today`;
const shot = (n) => (process.env.SHOT_DIR ? { path: `${process.env.SHOT_DIR}/${n}` } : {});
const dump = (n, d) => { if (process.env.SHOT_DIR) fs.writeFileSync(`${process.env.SHOT_DIR}/${n}`, JSON.stringify(d, null, 2)); };
test.use({ viewport: { width: 390, height: 844 } });

test("r11) 燕麥 500g/150g: eat 1 → 350g persists; cancel restores 500g", async ({ page }) => {
  await page.goto(url); await page.waitForSelector(".ttl");
  await page.locator("[data-tab=shop]").click();
  await page.locator("[data-testid=shop-plus]").click();
  await page.locator("[data-testid=shop-add] [data-shop-new-name]").fill("燕麥");
  await page.locator("[data-testid=shop-add] [data-shop-new-amount]").fill("500g");
  await page.locator("[data-shop-cat=starch]").click();
  await page.locator("[data-shop-add]").click();
  const item = async () => { const s = await page.evaluate(() => JSON.parse(localStorage.getItem("fatcat-v2") || "{}")); const it = (s.shopExtra || []).find((x) => x.name.startsWith("燕麥")); return { s, it }; };
  const { it } = await item(); const id = it.id;
  const pick = (s) => ({ item: s.shopExtra.find((x) => x.id === id), portion: (s.shopPortions || {})[id], used: (s.shopUsed || {})[id] ?? 0, dinner: ((s.mealLogs || {})["2026-11-10"] || {}).dinner || null });
  await page.locator(`[data-testid=shop-edit-${id}]`).click();
  await page.locator("[data-testid=edit-portion]").fill("150 g");
  await page.locator("[data-testid=edit-save]").click();
  await expect(page.locator(`[data-testid=shop-qty-${id}]`)).toHaveText("約 3.3 份");
  await page.locator("[data-tab=today]").click();
  await page.locator("[data-eat-else=dinner]").click();
  await page.locator(`[data-testid="else-inc-${id}"]`).click();
  await page.locator("[data-testid=else-save]").click();
  await page.locator("[data-tab=shop]").click();
  const sheet = async (tag) => {
    await expect(page.locator(`[data-testid=shop-qty-${id}]`)).toHaveText("約 2.3 份");
    await page.locator(`[data-testid=shop-edit-${id}]`).click();
    await expect(page.locator("[data-testid=edit-left]")).toHaveText("剩 350g");
    await expect(page.locator("[data-testid=edit-n]")).toHaveValue("2.3");
    await page.screenshot(shot(`fatmi_r11_${tag}.png`));
    await page.locator("[data-edit-close]").click();
  };
  await sheet("before_reload");
  dump("fatmi_r11_before_reload.json", pick((await item()).s));
  await page.reload(); await page.waitForSelector(".ttl");
  await page.locator("[data-tab=shop]").click();
  await sheet("after_reload");
  dump("fatmi_r11_after_reload.json", pick((await item()).s));
  // cancel the eat: tap ✓ 吃了 on dinner
  await page.locator("[data-tab=today]").click();
  await page.locator("[data-eat=dinner]").click();
  await page.reload(); await page.waitForSelector(".ttl");
  await page.locator("[data-tab=shop]").click();
  await expect(page.locator(`[data-testid=shop-qty-${id}]`)).toHaveText("約 3.3 份");
  await page.locator(`[data-testid=shop-edit-${id}]`).click();
  await expect(page.locator("[data-testid=edit-left]")).toHaveText("剩 500g");
  await page.screenshot(shot("fatmi_r11_cancel_after_reload.png"));
  dump("fatmi_r11_cancel_after_reload.json", pick((await item()).s));
});

test("r12) 吃了別的 logs chosen items' nutrition; cancel/re-tick exact; persists after reload", async ({ page }) => {
  await page.goto(url); await page.waitForSelector(".ttl");
  const rings = async () => (await page.locator("[data-testid=eat-card] .ring b").allInnerTexts()).map((x) => Number(x.replace(/[^\d.]/g, "")));
  await page.locator("[data-testid=eat-card] .ring b").first().waitFor();
  await expect.poll(async () => (await rings()).every((x) => !Number.isNaN(x))).toBe(true);
  const base = await rings();
  await page.locator("[data-tab=shop]").click();
  await page.locator("[data-testid=shop-plus]").click();
  await page.locator("[data-testid=shop-add] [data-shop-new-name]").fill("燕麥");
  await page.locator("[data-testid=shop-add] [data-shop-new-amount]").fill("500g");
  await page.locator("[data-shop-cat=starch]").click();
  await page.locator("[data-shop-add]").click();
  const id = await page.evaluate(() => JSON.parse(localStorage.getItem("fatcat-v2")).shopExtra.find((x) => x.name.startsWith("燕麥")).id);
  await page.locator(`[data-testid=shop-edit-${id}]`).click();
  await page.locator("[data-testid=edit-portion]").fill("150 g");
  await page.locator("[data-testid=edit-kcal]").fill("570");
  await page.locator("[data-testid=edit-prot]").fill("20");
  await page.locator("[data-testid=edit-save]").click();
  await page.locator("[data-tab=today]").click();
  await page.locator("[data-eat-else=dinner]").click();
  await page.locator(`[data-testid="else-inc-${id}"]`).click();
  await expect(page.locator("[data-testid=else-total]")).toContainText("570");
  await page.locator("[data-testid=else-save]").click();
  const row = page.locator("[data-testid=meal-dinner]");
  const eatenState = async (tag) => {
    await expect(row).toHaveClass(/eaten/);
    await expect(row.locator(".nums")).toHaveText("570 · 蛋白 20g");
    await expect.poll(async () => (await rings())[0]).toBe(base[0] + 570);
    const r = await rings();
    if (r.length > 1) expect(r[1]).toBe(base[1] + 20);
    await page.screenshot(shot(`fatmi_r12_${tag}.png`));
  };
  await eatenState("eaten");
  await page.reload(); await page.waitForSelector(".ttl");
  await eatenState("eaten_reload");
  await page.locator("[data-eat=dinner]").click(); // cancel
  await expect(row).not.toHaveClass(/eaten/);
  await expect(row.locator(".nums")).toHaveText("570 · 蛋白 20g");
  await page.reload(); await page.waitForSelector(".ttl");
  await expect.poll(rings).toEqual(base);
  await page.screenshot(shot("fatmi_r12_cancel_reload.png"));
  await page.locator("[data-tab=shop]").click();
  await expect(page.locator(`[data-testid=shop-qty-${id}]`)).toHaveText("約 3.3 份");
  await page.locator("[data-tab=today]").click();
  await page.locator("[data-eat=dinner]").click(); // re-tick
  await page.reload(); await page.waitForSelector(".ttl");
  await eatenState("retick_reload");
  await page.locator("[data-tab=shop]").click();
  await expect(page.locator(`[data-testid=shop-qty-${id}]`)).toHaveText("約 2.3 份");
});

test("r13) Nutri flow: add 燕麥 via pantry form (category explicit), unknown nutrition → 待確認, card shows chosen, reopen prefilled; reload each step", async ({ page }) => {
  const rl = async (tab) => { await page.reload(); await page.waitForSelector(".ttl"); if (tab) await page.locator(`[data-tab=${tab}]`).click(); };
  await page.goto(url); await page.waitForSelector(".ttl");
  await page.locator("[data-tab=shop]").click();
  await page.locator("[data-testid=shop-plus]").click();
  await page.locator("[data-testid=shop-add] [data-shop-new-name]").fill("燕麥");
  await page.locator("[data-testid=shop-add] [data-shop-new-amount]").fill("500g");
  await expect(page.locator("[data-testid=shop-cat-protein]")).not.toHaveClass(/\bon\b/);
  await expect(page.locator("[data-testid=shop-cat-starch] [data-sug]")).toBeVisible();
  await page.locator("[data-shop-add]").click();
  await expect(page.locator("[data-testid=shop-cat-missing]")).toHaveText("請先選分類");
  await page.screenshot(shot("fatmi_r13_add_form.png"));
  await page.locator("[data-testid=shop-cat-starch]").click();
  await page.locator("[data-shop-add]").click();
  const s0 = await page.evaluate(() => JSON.parse(localStorage.getItem("fatcat-v2")));
  const it = s0.shopExtra.find((x) => x.name.startsWith("燕麥"));
  expect(it.group).toBe("starch");
  const id = it.id;
  await rl("shop");
  await expect(page.locator(`[data-testid=shop-nutri-pend-${id}]`)).toHaveText("待確認");
  await page.locator(`[data-testid=shop-edit-${id}]`).click();
  await page.locator("[data-testid=edit-portion]").fill("150 g");
  await expect(page.locator("[data-testid=edit-nutri-pend]")).toBeVisible();
  await page.locator("[data-testid=edit-save]").click();
  await rl("today");
  await page.locator("[data-eat-else=dinner]").click();
  await expect(page.locator(`[data-testid="else-pend-${id}"]`)).toHaveText("待確認");
  await page.locator(`[data-testid="else-inc-${id}"]`).click();
  await expect(page.locator("[data-testid=else-total]")).toContainText("0 kcal");
  await page.locator("[data-testid=else-save]").click();
  const row = page.locator("[data-testid=meal-dinner]");
  await expect(row.locator(".nums")).toHaveText("0 · 蛋白 0g");
  await expect(row.locator("[data-testid=meal-pick-dinner]")).toContainText("燕麥 1 份");
  await expect(row.locator("[data-testid=meal-pend-dinner]")).toHaveText("待確認");
  await expect(row.locator(".suggest")).toHaveCount(0);
  await rl();
  await expect(row.locator("[data-testid=meal-pick-dinner]")).toContainText("燕麥 1 份");
  await expect(row.locator("[data-testid=meal-pend-dinner]")).toHaveText("待確認");
  await expect(row.locator(".nums")).toHaveText("0 · 蛋白 0g");
  await row.scrollIntoViewIfNeeded();
  await page.screenshot(shot("fatmi_r13_card_pending.png"));
  // set nutrition, reopen 吃了別的: prefilled 1, re-save → real values
  await page.locator("[data-tab=shop]").click();
  await page.locator(`[data-testid=shop-edit-${id}]`).click();
  await page.locator("[data-testid=edit-kcal]").fill("570");
  await page.locator("[data-testid=edit-prot]").fill("20");
  await page.locator("[data-testid=edit-save]").click();
  await rl("shop");
  await expect(page.locator(`[data-testid=shop-nutri-pend-${id}]`)).toHaveCount(0);
  await expect(page.locator(`[data-testid=shop-qty-${id}]`)).toHaveText("約 2.3 份");
  await page.locator("[data-tab=today]").click();
  await page.locator("[data-eat-else=dinner]").click();
  await expect(page.locator(`[data-testid="else-n-${id}"]`)).toHaveText("1");
  await page.screenshot(shot("fatmi_r13_reopen_prefill.png"));
  await page.locator("[data-testid=else-save]").click();
  await expect(row.locator(".nums")).toHaveText("570 · 蛋白 20g");
  await expect(row.locator("[data-testid=meal-pend-dinner]")).toHaveCount(0);
  await rl("shop");
  await expect(page.locator(`[data-testid=shop-qty-${id}]`)).toHaveText("約 2.3 份");
  await page.locator("[data-tab=today]").click();
  await expect(row.locator(".nums")).toHaveText("570 · 蛋白 20g");
  await expect(row.locator("[data-testid=meal-pick-dinner]")).toHaveText("燕麥 1 份");
  await row.scrollIntoViewIfNeeded();
  await page.screenshot(shot("fatmi_r13_card_final.png"));
});
